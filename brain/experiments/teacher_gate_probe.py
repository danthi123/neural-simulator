"""No-training gate for the hippocampus-as-teacher night: is the awake brain a good enough teacher for its own cues?

A fresh brain (birth state, no sleep) is told the 12 shared facts through Brain.hear. Then the cues a teacher night
would use are generated by the pretrained cortex itself, as the near-miss guard does (brain/near_miss.py):
  own    for each stored telling, the cortex's own question about it (OWN frame, greedy);
  frame  its "my X" completions of the five onsets (frame_cues, k per onset, seeded).
For every cue the TEACHER answers: the pretrained cortex from the birth state, plus the episode the brain's own recall
returns, reinstated at the brain's gain (nothing reinstated when recall returns none); greedy, 24 tokens. Read-outs:
  own cues   teacher reply is a correct answer for that telling's key (strict_scorer.correct_answer, as the probes);
  frame cues split by told_topic (the M4b brain-side rule): told-topic cues, right key; never-told cues, any told key
             in the reply = a false answer the teacher would teach.
Recall's use boost is undone after each cue (the gate changes nothing). No reply of the probe's test questions is
read; their overlap with the generated cues is reported.

  python -m brain.experiments.teacher_gate_probe --seed 42 --out <json> [--k 4]
"""
import argparse
import json
import os
import shutil
import tempfile

import torch

from brain.brain import Brain
from brain.cortex import Cortex, resolve_model
from brain.experiments.facts import FACTS, PARA
from brain.experiments.sleep_probe import NEVER_TOLD
from brain.experiments.strict_scorer import correct_answer, has_key
from brain.near_miss import frame_cues, near_miss_cues, told_topic


def teacher(b, q):
    h = b.hippocampus
    saved = [(e.strength, e.uses, e.last_used) for e in h.episodes]
    ep, sim = h.recall(b.cortex, b.base, q, question=q.endswith("?"))
    for e, s in zip(h.episodes, saved):
        e.strength, e.uses, e.last_used = s
    state = h.reinstate(b.raw_cortex, [s.clone() for s in b.base], ep) if ep is not None else b.base
    lg, st = b.raw_cortex.read(f"User: {q}\n\nAssistant:", state)
    reply = b.raw_cortex.speak(lg, st, max_tokens=24, temperature=0)[0]
    return reply, (ep.text if ep is not None else None), round(float(sim), 4)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--model", default="1.5b")
    ap.add_argument("--seed", type=int, required=True)
    ap.add_argument("--k", type=int, default=4)
    ap.add_argument("--out", required=True)
    ap.add_argument("--threads", type=int, default=0)
    a = ap.parse_args()
    if a.threads:
        torch.set_num_threads(a.threads)
    torch.manual_seed(a.seed)
    c = Cortex(model_path=resolve_model(a.model), device="cpu")
    root = tempfile.mkdtemp(dir=os.path.dirname(os.path.abspath(a.out)))
    b = Brain(f"{root}/home", cortex=c, sleep_on_restart=False, sleep_seed=a.seed)
    tell = [{"you": f, "brain": b.hear(f)[0]} for f, _, _ in FACTS]
    told_eps = [e for e in b.hippocampus.episodes if not e.permanent]
    keys = {f: k for f, _, k in FACTS}
    rows = []
    for i, e in enumerate(told_eps):
        stmt = e.text.split("\n\nAssistant:")[0].removeprefix("User: ").strip()   # the user's words
        own, _ = near_miss_cues(b.raw_cortex, b.base, stmt, k=1, seed=a.seed * 100 + i)
        own = own.removeprefix("User:").strip()
        key = next((k for f, k in keys.items() if f in e.text), None)
        r, rec, sim = teacher(b, own)
        rows.append({"kind": "own", "telling": e.text, "q": own, "key": key, "reply": r, "recalled": rec, "sim": sim,
                     "ok": bool(key) and bool(correct_answer(r, key, own, stmt))})
    told_texts = [e.text for e in told_eps]
    for q in frame_cues(b.raw_cortex, b.base, k=a.k, seed=a.seed):
        r, rec, sim = teacher(b, q)
        tt = told_topic(q, told_texts)
        hit = [k for k in keys.values() if has_key(r, k) and not has_key(q, k)]
        rows.append({"kind": "frame_told" if tt else "frame_never", "q": q, "reply": r, "recalled": rec, "sim": sim,
                     "told_keys_in_reply": hit})
    tests = {q.lower() for _, q, _ in FACTS} | {q.lower() for q in PARA} | {q.lower() for q in NEVER_TOLD}
    overlap = sorted({r["q"] for r in rows if r["q"].lower() in tests})
    own = [r for r in rows if r["kind"] == "own"]
    never = [r for r in rows if r["kind"] == "frame_never"]
    summary = {"own_ok": sum(r["ok"] for r in own), "own_n": len(own),
               "never_false": sum(bool(r["told_keys_in_reply"]) for r in never), "never_n": len(never),
               "frame_told_n": sum(r["kind"] == "frame_told" for r in rows), "overlap_with_tests": overlap,
               "gain": b.hippocampus.GAIN}
    print(json.dumps(summary), flush=True)
    b.release()
    shutil.rmtree(root, ignore_errors=True)
    json.dump({"model": c.model_name, "host": os.uname().nodename, "seed": a.seed, "k": a.k, "summary": summary,
               "tell": tell, "rows": rows}, open(a.out, "w"), indent=1)


if __name__ == "__main__":
    main()
