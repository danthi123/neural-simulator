_BANNED = ["sad", "happy", "upset", "angry", "excited", "devastated", "thrilled",
           "sorry", "glad", "love", "hate", "terrible", "awful", "wonderful",
           "great", "amazing", "horrible", "miserable", "delighted", "scared",
           "afraid", "worried", "lonely", "depressed", "grief", "joy"]


def _check():
    import re
    want = {
        "DEV_FIT": {"NEG": 40, "NEU": 40, "SNEU": 20, "HARD": 20, "POS": 20},
        "DEV_VAL": {"NEG": 20, "NEU": 20, "SNEU": 10, "HARD": 10, "POS": 10},
        "DEV_CONV": {"NEG": 12, "NEU": 12, "SNEU": 12},
        "TEST": {"NEG": 16, "NEU": 16, "SNEU": 16, "POS": 16},
        "EVERYDAY": {"tellings": 24, "badnews": 12},
    }
    allsent = []
    counts = {}
    for b, spec in want.items():
        for k, n in spec.items():
            lst = BANKS[b][k]
            assert len(lst) == n, (b, k, len(lst), n)
            counts[f"{b}.{k}"] = len(lst)
            allsent += lst
    assert len(allsent) == len(set(allsent)), "duplicates"
    pat = re.compile(r"\b(" + "|".join(_BANNED) + r")\b", re.I)
    for s in allsent:
        n = len(s.split())
        assert 6 <= n <= 16, (n, s)
        assert s.endswith("."), s
        assert "!" not in s, s
        assert not pat.search(s), s
    return counts


