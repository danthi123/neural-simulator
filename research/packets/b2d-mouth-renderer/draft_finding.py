#!/usr/bin/env python3
"""draft_finding.py -- write B2d's PROVISIONAL finding from the two scorer outputs, with no judgment in the prose.

  python research/packets/b2d-mouth-renderer/draft_finding.py --pin <P> \
      --stub research/findings/raw/_load_bearing/_shards/b2d0929/b2d_score.json \
      --mouth research/findings/raw/_load_bearing/_shards/b2d0929-mouth/b2d_mouth_score.json --out <finding.md>

Every number comes from the two JSON files; every sentence that states a result is a fixed template whose only
variables are those numbers and the registered labels. The labels the pre-registration requires ("at P", "stub
renderer", the mouth arm reported separately) are always written. The predictions compared are Amendment 1's A1.3.
"""
import argparse
import datetime
import json
import os
import sys

PREREG = "research/findings/2026-09-29-production-default-battery-B2d-PREREGISTRATION.md"
PREDICTED = {"affect-coloring": "MOUTH-SILENT", "affect-appraisal-interoceptive": "MOUTH-SILENT",
             "affect-drives-response": "MOUTH-NOT-LOAD-BEARING"}


def _f(x, nd=3):
    return "n/a" if x is None else ("%.*f" % (nd, x))


def _count(v):
    return str(v) if isinstance(v, int) else ("%d-%d (interval: undefined cells)" % (v[0], v[1]))


def level_block(name, lvl, seeds):
    out = ["**%s**: mean fraction %s, population SD %s; robust core %d (%s); union %d." % (
        name, _f(lvl.get("mean_fraction")), _f(lvl.get("sd_fraction_pop")), lvl.get("robust_core_n", 0),
        ", ".join(lvl.get("robust_core") or []) or "none", lvl.get("union_n", 0)), "",
        "| seed | defined | exercised | load-bearing | fraction |", "|---|---|---|---|---|"]
    for s in seeds:
        p = (lvl.get("per_seed") or {}).get(str(s), {})
        out.append("| %s | %s | %s | %s | %s |" % (s, p.get("n_defined"), p.get("n_exercised"),
                                                   p.get("n_load_bearing"), _f(p.get("fraction"))))
    return out


def build(pin, stub, mouth):
    p7 = pin[:7]
    seeds = stub.get("seeds") or [42, 43, 44, 100, 101, 102]
    s0, s1, s2 = stub.get("s0", {}), stub.get("s1", {}), stub.get("s2", {})
    pre_fail = [p["name"] for p in stub.get("preconditions", []) if p.get("ok") is not True]
    m_pre_fail = [p["name"] for p in mouth.get("preconditions", []) if p.get("ok") is not True]
    drift = stub.get("drift") or {}
    lines = [
        "---",
        "type: finding",
        "status: provisional",
        "claim_check: measured (tools/b2d_score.py and tools/b2d_mouth_score.py over the landed shards; prose "
        "generated by research/packets/b2d-mouth-renderer/draft_finding.py; awaiting Claude review)",
        "date: %s" % datetime.date.today().isoformat(),
        "lane: load-bearing (the #1 metric, owner 2026-09-19; reply level, owner 2026-08-19)",
        "mechanism: Battery B2d at P=%s -- the 50-row registry at the production default, scored three ways (S0 raw, "
        "S1 self-describing fields excluded = headline, S2 reply-level) with the stub renderer, plus the mouth arm "
        "(three affect rows through the production Qwen mouth) reported separately" % pin,
        "seeds: [%s]" % ", ".join(str(s) for s in seeds),
        "artifacts:",
        "  - research/findings/raw/_load_bearing/_shards/b2d0929/ (lb.json + arm files per cell; b2d_score.json)",
        "  - research/findings/raw/_load_bearing/_shards/b2d0929-mouth/ (lb.json + arm files per cell; "
        "b2d_mouth_score.json)",
        "  - research/coordination/b2d_decision_fields.json (the SD audit S1 reads)",
        "  - %s (the pre-registration and its Amendment 1)" % PREREG,
        "verdict: PROVISIONAL. Stub arm %s; S1 (headline) mean %s, SD %s, robust core %d; S0 mean %s, robust core %d; "
        "S2 mean %s, robust core %d; all at P=%s, stub renderer. Mouth arm %s (reported separately)." % (
            stub.get("verdict"), _f(s1.get("mean_fraction")), _f(s1.get("sd_fraction_pop")), s1.get("robust_core_n", 0),
            _f(s0.get("mean_fraction")), s0.get("robust_core_n", 0), _f(s2.get("mean_fraction")),
            s2.get("robust_core_n", 0), p7, mouth.get("verdict")),
        "---",
        "",
        "# Battery B2d at P=%s (stub renderer; the mouth arm reported separately) -- PROVISIONAL" % p7,
        "",
        "Pre-registration: `%s` (main text and Amendment 1). Pin P = `%s`. Every figure below is \"at P\" and, for "
        "the stub arm, \"stub renderer\". This document was generated from the scorer outputs and has not been "
        "reviewed by Claude." % (PREREG, pin),
        "",
        "## Stub arm (tag b2d0929)",
        "",
        "Battery verdict (A1.5): **%s**. Coverable cells: %s; DEFINED: %s. Scorer preconditions failed: %s." % (
            stub.get("verdict"), (stub.get("counts") or {}).get("n_coverable_cells"),
            (stub.get("counts") or {}).get("n_defined"), ", ".join(pre_fail) or "none"),
        "",
    ]
    lines += level_block("S1, self-describing fields excluded (headline, the #1 metric at P)", s1, seeds) + [""]
    lines += level_block("S0, raw (as registered)", s0, seeds) + [""]
    lines += level_block("S2, reply-level (answer / abstained / recalled_svo on the probe turn)", s2, seeds) + [""]
    lines += ["sd-only rows (S1 UNDEFINED:sd-only, registry defects for their lanes, never 0): %s." % (
        ", ".join(stub.get("sd_only_rows") or []) or "none"), ""]
    facs = sorted(set((s0.get("per_faculty") or {})) | set((s1.get("per_faculty") or {})))
    lines += ["### Per faculty (load-bearing seeds of 6; an interval where cells are undefined)", "",
              "| faculty | S0 | S1 | S2 |", "|---|---|---|---|"]
    for f in facs:
        g = lambda lvl: _count(((lvl.get("per_faculty") or {}).get(f) or {}).get("n_load_bearing", "n/a"))  # noqa
        lines.append("| %s | %s | %s | %s |" % (f, g(s0), g(s1), g(s2)))
    lines += ["", "### Cells not DEFINED, FAIL cells, organ errors", ""]
    nd = stub.get("not_defined") or {}
    lines.append("Not DEFINED: %d%s" % (len(nd), (": " + "; ".join("%s (%s)" % (k, v.get("state")) for k, v in
                                                                    sorted(nd.items()))) if nd else "."))
    lines.append("")
    lines.append("FAIL cells: %s." % (", ".join(stub.get("fail_cells") or []) or "none"))
    lines.append("")
    oe = stub.get("organ_error_cells") or {}
    lines.append("Rule-7 organ-error cells: %s." % (", ".join(sorted(oe)) or "none"))
    lines += ["", "### Drift from B2b (reported, not gated)", ""]
    if drift:
        lines.append("Cells DEFINED in both: %s; cells whose S0, S1 or S2 differ: %s." % (
            drift.get("n_common_defined_cells"), drift.get("n_differing")))
        lines.append("")
        for d in drift.get("differences") or []:
            lines.append("- %s: %s" % (d.get("cell"), json.dumps({k: v for k, v in d.items() if k != "cell"})))
        lines.append("")
        lines.append("Named in advance (prereg, \"Comparison with B2b\"): affect-marker-spiking-wta's S2 was expected "
                     "to stop changing (the marker word is off the surface since 969894855). Any other listed "
                     "difference is a default-path change between F and P that its commit did not announce; it is "
                     "reported with the commit range, without bisection.")
    else:
        lines.append("No drift block in the scorer output.")
    lines += ["", "## Mouth arm (tag b2d0929-mouth; production Qwen mouth, cupy) -- reported separately", "",
              "Verdict: **%s**. Scorer preconditions failed: %s." % (mouth.get("verdict"),
                                                                    ", ".join(m_pre_fail) or "none"), "",
              "| row | probe turn | reading | predicted (A1.3) | as predicted | reply-load-bearing / exercised | "
              "mouth-silent | FAIL |", "|---|---|---|---|---|---|---|---|"]
    for row, r in sorted((mouth.get("per_row") or {}).items()):
        pred = PREDICTED.get(row, "n/a")
        lines.append("| %s | %s | %s | %s | %s | %s / %s | %s | %s |" % (
            row, r.get("probe_turn"), r.get("reading"), pred, "yes" if r.get("reading") == pred else "no",
            r.get("n_reply_load_bearing"), r.get("n_reply_exercised"), r.get("n_mouth_silent"), r.get("n_fail")))
    lines += ["", "Per cell (state, S2 through the mouth, Qwen generation calls per arm; the stub arm's S2 for the "
              "same cell beside it):", ""]
    for k, c in sorted((mouth.get("cells") or {}).items()):
        lines.append("- %s: %s, mouth S2 %s, qwen calls %s, stub S2 %s" % (
            k, c.get("final"), (c.get("s2") or [None])[0], json.dumps(c.get("qwen_calls")),
            (c.get("stub") or {}).get("s2")))
    lines += ["", "## What this licenses", "",
              "Reporting the #1 metric at P: S1 over the full registry at the production default, per seed with mean "
              "and SD, robust core, union and each faculty's count, with S0 and S2 beside it, all at P with the stub "
              "renderer; and, separately, whether the three affect rows change the reply the production mouth "
              "writes on their registered turns. It licenses no default flip, no claim about who composed a reply, "
              "and nothing about probes outside the registered set (prereg, \"What a COMPLETE verdict licenses\").",
              ""]
    return "\n".join(lines) + "\n"


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--pin", required=True)
    ap.add_argument("--stub", required=True)
    ap.add_argument("--mouth", required=True)
    ap.add_argument("--out", required=True)
    a = ap.parse_args(argv)
    text = build(a.pin, json.load(open(a.stub)), json.load(open(a.mouth)))
    os.makedirs(os.path.dirname(os.path.abspath(a.out)), exist_ok=True)
    with open(a.out, "w") as fh:
        fh.write(text)
    print("wrote %s (%d lines)" % (a.out, text.count("\n")))
    return 0


if __name__ == "__main__":
    sys.exit(main())
